"""Render grouped comparison or check/cross ablation tables from JSON.

Uses only supplied results; does not calculate or invent missing SDs.
Usage: python render_paper_table.py config.json
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import re


def tex(text):
    escapes = {'\\': r'\textbackslash{}', '&': r'\&', '%': r'\%', '$': r'\$',
               '#': r'\#', '_': r'\_', '{': r'\{', '}': r'\}', '~': r'\textasciitilde{}', '^': r'\textasciicircum{}'}
    return ''.join(escapes.get(c, c) for c in str(text))


def number(value):
    if isinstance(value, bool) or not isinstance(value, (float, int)) or not math.isfinite(value):
        raise ValueError('Metrics must be finite numbers, never placeholder text')
    return value


def unpack(value):
    if isinstance(value, list):
        if len(value) != 2: raise ValueError('Uncertainty cell must be [mean, SD]')
        mean, sd = map(number, value)
        if sd < 0: raise ValueError('SD cannot be negative')
        return mean, sd
    return number(value), None


def heading(value):
    parts = str(value).split('\n')
    return tex(value) if len(parts) == 1 else r'\shortstack{' + r'\\'.join(tex(p) for p in parts) + '}'


def render(config_path):
    path = Path(config_path).resolve()
    cfg = json.loads(path.read_text(encoding='utf-8'))
    rows, groups, metrics = cfg['rows'], cfg['groups'], cfg['metrics']
    components = cfg.get('components', [])
    if not rows or not groups or not metrics: raise ValueError('Supply real rows, groups and metrics')
    if any(m['direction'] not in ('min', 'max') for m in metrics): raise ValueError('Metric direction must be min or max')
    for items in (groups, metrics, components):
        keys = [v['key'] for v in items]
        if len(set(keys)) != len(keys): raise ValueError('Duplicate schema keys')
    digits = cfg.get('digits', 2)
    if not isinstance(digits, int) or not 0 <= digits <= 6: raise ValueError('Invalid precision')
    label = cfg['label']
    if not re.fullmatch(r'[A-Za-z0-9:_-]+', label): raise ValueError('Invalid LaTeX label')
    ranks = {}
    for g in groups:
        for m in metrics:
            values = [round(unpack(r['values'][g['key']][m['key']])[0], digits) for r in rows]
            ranks[g['key'], m['key']] = sorted(set(values), reverse=m['direction'] == 'max')
    head = len(components) or 1
    nmetrics = len(metrics)
    # Centering X/m columns and a centered method column reproduce accepted tables.
    def xcolumn(weight):
        return r'>{\hsize='+f'{weight:.8f}'+r'\hsize\linewidth=\hsize\centering\arraybackslash}X'
    if components:
        component_weight = .67
        numeric_weight = (len(components)+len(groups)*nmetrics-len(components)*component_weight)/(len(groups)*nmetrics)
        prefix = xcolumn(component_weight)*len(components)
    else:
        numeric_weight = 1
        prefix = 'c'
    # Normalize optional metric width weights to keep tabularx's total hsize unchanged.
    metric_weights = [number(m.get('width_weight',1)) for m in metrics]
    if min(metric_weights) <= 0: raise ValueError('Column width weights must be positive')
    metric_columns = ''.join(xcolumn(numeric_weight*w*nmetrics/sum(metric_weights)) for w in metric_weights)
    columns = prefix + '|' + '|'.join(metric_columns for _ in groups)
    env = 'table*' if cfg.get('wide', True) else 'table'
    width = r'\textwidth' if cfg.get('wide', True) else r'\columnwidth'
    lines = [r'% Generated by render_paper_table.py. Requires approved-paper-tables.sty.',
             '\\begin{'+env+'}[!t]', r'\ApprovedTableSetup',
             r'\caption{'+tex(cfg['caption'].upper())+'}', r'\label{'+label+'}',
             r'\centering', r'\linespread{1}\selectfont',
             '\\fontsize{'+str(cfg.get('font_size', 8))+'}{'+str(cfg.get('baseline_skip', 9.6))+'}\\selectfont',
             '\\setlength{\\tabcolsep}{'+str(cfg.get('tabcolsep', 3))+'pt}',
             r'\renewcommand{\arraystretch}{1.20}',
             r'\setlength{\aboverulesep}{1.3pt}', r'\setlength{\belowrulesep}{1.3pt}',
             r'\begin{threeparttable}', r'\renewcommand{\tabularxcolumn}[1]{m{#1}}',
             r'\begin{tabularx}{'+width+'}{'+columns+'}', r'\toprule']
    first = r'\multicolumn{'+str(head)+r'}{c|}{\textbf{Components}}' if components else r'\multirow{2}{*}[-1.5pt]{\textbf{Method}}'
    headings = [first]
    for i, g in enumerate(groups):
        headings.append(r'\multicolumn{'+str(nmetrics)+'}{c'+('|' if i+1 < len(groups) else '')+r'}{\textbf{'+tex(g['label'])+'}}')
    lines.append(' & '.join(headings)+r'\\')
    rules = r'\cmidrule(lr){1-'+str(head)+'}' if components else ''
    for i in range(len(groups)):
        start = head+i*nmetrics+1
        rules += r'\cmidrule(lr){'+str(start)+'-'+str(start+nmetrics-1)+'}'
    lines.append(rules)
    headers = [heading(c['label']) for c in components] if components else ['']
    for _ in groups:
        headers.extend(heading(m['label'])+(' $\\downarrow$' if m['direction']=='min' else ' $\\uparrow$') for m in metrics)
    lines.extend([' & '.join(headers)+r'\\', r'\midrule'])
    for row in rows:
        if row.get('proposed', False): lines.extend([r'\midrule', r'\rowcolor{ApprovedTableOurs}'])
        if components:
            cells = []
            for c in components:
                val = row['components'][c['key']]
                if type(val) is not bool: raise ValueError('Component flags must be boolean')
                cells.append(r'$\checkmark$' if val else r'$\times$')
        else:
            name = tex(row['name'])
            if row.get('proposed', False): name = r'\textbf{'+name+'}'
            if row.get('citation'):
                if not re.fullmatch(r'[A-Za-z0-9:_,-]+', row['citation']): raise ValueError('Invalid citation key')
                name += r'~\cite{'+row['citation']+'}'
            cells = [name]
        for g in groups:
            for m in metrics:
                mean, sd = unpack(row['values'][g['key']][m['key']])
                value = f'{mean:.{digits}f}'
                ranking = ranks[g['key'], m['key']]
                if cfg.get('rank', True):
                    if round(mean, digits) == ranking[0]: value = r'\mathbf{'+value+'}'
                    elif len(ranking)>1 and round(mean,digits)==ranking[1]: value = r'\underline{'+value+'}'
                if sd is not None: value += r'\,{\scriptstyle\pm'+f'{sd:.{digits}f}'+'}'
                cells.append('$'+value+'$')
        lines.append(' & '.join(cells)+r'\\')
    lines.extend([r'\bottomrule', r'\end{tabularx}'])
    if cfg.get('note'):
        lines.extend([r'\begin{tablenotes}[flushleft]', r'\fontsize{7}{8.4}\selectfont',
                      r'\item '+tex(cfg['note']), r'\end{tablenotes}'])
    lines.extend([r'\end{threeparttable}', '\\end{'+env+'}'])
    output = (path.parent / cfg['output']).resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines)+'\n', encoding='utf-8')
    Path(str(output)+'.audit.json').write_text(json.dumps({
        'config_sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
        'renderer_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        'rounding': digits, 'ranking': 'distinct displayed means; ties share rank',
        'config': cfg}, indent=2), encoding='utf-8')
    print(f'Saved {output}; supplied means/SDs preserved apart from display rounding.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('config')
    render(parser.parse_args().config)